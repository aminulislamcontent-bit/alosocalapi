#!/usr/bin/env node
import { randomBytes } from 'node:crypto';
import { spawn, spawnSync } from 'node:child_process';
import { chmodSync, closeSync, existsSync, mkdirSync, openSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { inspectExistingDatabase, inspectMigrationReadiness, sqliteFileFromDatabaseUrl } from './migrations.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENV_FILE = path.join(ROOT, '.env');
const STATE_DIR = process.env.ALOAPI_STATE_DIR || path.join(homedir(), '.aloapi');
const PID_FILE = path.join(STATE_DIR, 'service.json');
const LOG_FILE = path.join(STATE_DIR, 'aloapi.log');
const DEFAULT_HOST = '127.0.0.1';
const DEFAULT_PORT = 47831;
const NEXT_BIN = path.join(ROOT, 'node_modules', 'next', 'dist', 'bin', 'next');
const STANDALONE_SERVER = path.join(ROOT, '.next', 'standalone', 'server.js');

export function parsePort(value, fallback = DEFAULT_PORT) {
  if (value === undefined || value === null || value === '') return fallback;
  const port = Number(value);
  if (!Number.isInteger(port) || port < 1024 || port > 65535) throw new Error('ALOAPI_PORT must be an integer from 1024 to 65535.');
  return port;
}

export function isLoopbackHost(host) {
  return ['127.0.0.1', 'localhost', '::1'].includes(String(host).toLowerCase());
}

export function parseEnvFile(content) {
  const values = {};
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const match = /^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!match) continue;
    let value = match[2].trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) value = value.slice(1, -1);
    values[match[1]] = value;
  }
  return values;
}

export function browserInvocation(platform, url) {
  if (platform === 'win32') return { command: 'cmd.exe', args: ['/c', 'start', '', url] };
  if (platform === 'darwin') return { command: 'open', args: [url] };
  return { command: 'xdg-open', args: [url] };
}

export function serviceUrl(port = DEFAULT_PORT, host = DEFAULT_HOST) {
  const displayHost = host === '::1' ? '[::1]' : host;
  return `http://${displayHost}:${port}`;
}

function loadLocalEnv() {
  if (!existsSync(ENV_FILE)) return;
  const values = parseEnvFile(readFileSync(ENV_FILE, 'utf8'));
  for (const [key, value] of Object.entries(values)) if (process.env[key] === undefined) process.env[key] = value;
}

function writeInitialEnv() {
  if (existsSync(ENV_FILE)) return null;
  const username = 'aloapi-admin';
  const password = randomBytes(24).toString('base64url');
  const vaultKey = randomBytes(32).toString('base64url');
  const lines = [
    '# Generated by `npm run aloapi -- setup`. Keep this file private and out of Git.',
    'DATABASE_URL="file:./db/custom.db"',
    `ALOAPI_HOST="${DEFAULT_HOST}"`,
    `ALOAPI_PORT="${DEFAULT_PORT}"`,
    `ALOAPI_BASE_URL="http://${DEFAULT_HOST}:${DEFAULT_PORT}"`,
    `ALOAPI_VAULT_KEY="${vaultKey}"`,
    `ADMIN_BOOTSTRAP_USERNAME="${username}"`,
    `ADMIN_BOOTSTRAP_PASSWORD="${password}"`,
    'ALOAPI_REQUIRE_ADMIN_MFA="false"',
    'ALOAPI_TRUST_PROXY="false"',
    'ALOAPI_PUBLIC_WEBHOOK_BASE_URL=""',
    '',
  ];
  writeFileSync(ENV_FILE, lines.join('\n'), { flag: 'wx', mode: 0o600 });
  try { chmodSync(ENV_FILE, 0o600); } catch { /* Windows ACLs are managed by the OS. */ }
  return { username, password };
}

function runtimeConfig() {
  loadLocalEnv();
  const host = process.env.ALOAPI_HOST || DEFAULT_HOST;
  if (!isLoopbackHost(host)) throw new Error('ALOAPI_HOST must be loopback-only (127.0.0.1, localhost, or ::1). Public interfaces are not supported by this local CLI.');
  const port = parsePort(process.env.ALOAPI_PORT, DEFAULT_PORT);
  const url = serviceUrl(port, host);
  return { host, port, url, instanceId: process.env.ALOAPI_INSTANCE_ID || randomBytes(16).toString('hex') };
}

function requireVaultKey() {
  if (!process.env.ALOAPI_VAULT_KEY || Buffer.byteLength(process.env.ALOAPI_VAULT_KEY, 'utf8') < 32) {
    throw new Error('Set a stable ALOAPI_VAULT_KEY of at least 32 UTF-8 bytes before startup; no database migration was attempted.');
  }
}

function ensureStateDir() {
  mkdirSync(STATE_DIR, { recursive: true, mode: 0o700 });
  try { chmodSync(STATE_DIR, 0o700); } catch { /* Windows ACLs are managed by the OS. */ }
}

async function requestHealth(url) {
  try {
    const response = await fetch(`${url}/api/health`, { signal: AbortSignal.timeout(1200), cache: 'no-store' });
    const body = await response.json().catch(() => null);
    return body?.service === 'aloapi' ? body : null;
  } catch {
    return null;
  }
}

function runCommand(command, args, label) {
  const result = spawnSync(command, args, { cwd: ROOT, stdio: 'inherit', env: process.env, shell: process.platform === 'win32' });
  if (result.error) throw new Error(`${label} could not start: ${result.error.message}`);
  if (result.status !== 0) throw new Error(`${label} failed with exit code ${result.status ?? 'unknown'}.`);
}

function npmCommand() {
  return process.platform === 'win32' ? 'npm.cmd' : 'npm';
}

function runServerForeground(dev, config) {
  const args = dev
    ? [NEXT_BIN, 'dev', '--hostname', config.host, '--port', String(config.port)]
    : [STANDALONE_SERVER];
  if (!dev && !existsSync(STANDALONE_SERVER)) throw new Error('Production build not found. Run `npm run aloapi -- start` or `npm run build` first.');
  const child = spawn(process.execPath, args, {
    cwd: ROOT,
    stdio: 'inherit',
    env: { ...process.env, NODE_ENV: dev ? 'development' : 'production', HOSTNAME: config.host, PORT: String(config.port), ALOAPI_INSTANCE_ID: config.instanceId },
  });
  const forwardSignal = signal => {
    if (child.exitCode === null && child.signalCode === null) child.kill(signal);
  };
  const onInterrupt = () => forwardSignal('SIGINT');
  const onTerminate = () => forwardSignal('SIGTERM');
  child.on('error', error => { console.error(`ALOAPI server failed: ${error.message}`); process.exitCode = 1; });
  child.on('exit', (code, signal) => {
    process.off('SIGINT', onInterrupt);
    process.off('SIGTERM', onTerminate);
    process.exitCode = signal === 'SIGINT' ? 130 : signal === 'SIGTERM' ? 143 : code ?? 1;
  });
  process.on('SIGINT', onInterrupt);
  process.on('SIGTERM', onTerminate);
}

async function startBackground({ dev, noOpen }) {
  const created = writeInitialEnv();
  if (created) {
    console.log(`Created private local configuration at ${ENV_FILE}.`);
    console.log(`One-time administrator username: ${created.username}`);
    console.log(`One-time administrator password: ${created.password}`);
    console.log('Save these credentials now. Remove ADMIN_BOOTSTRAP_USERNAME and ADMIN_BOOTSTRAP_PASSWORD from .env after first login.');
  }
  loadLocalEnv();
  const config = runtimeConfig();
  requireVaultKey();
  ensureStateDir();
  const already = await requestHealth(config.url);
  if (already) {
    if (already.status !== 'ok') throw new Error(`An ALOAPI service already responds at ${config.url}, but its database is ${already.database ?? 'unavailable'}. No second service was started.`);
    console.log(`ALOAPI is already responding at ${config.url} (database: ${already.database ?? 'unknown'}).`);
    if (!noOpen) openBrowser(config.url);
    return;
  }

  if (existsSync(PID_FILE)) {
    try {
      const previous = JSON.parse(readFileSync(PID_FILE, 'utf8'));
      if (Number.isInteger(previous.pid)) {
        try { process.kill(previous.pid, 0); console.error(`A previous ALOAPI process may still be running (PID ${previous.pid}); inspect [36m${LOG_FILE}[0m before starting another.`); process.exitCode = 1; return; }
        catch { rmSync(PID_FILE, { force: true }); }
      }
    } catch { rmSync(PID_FILE, { force: true }); }
  }

  const migrationDir = path.join(ROOT, 'prisma', 'migrations');
  if (!existsSync(migrationDir) || !readFileSync(path.join(migrationDir, 'migration_lock.toml'), 'utf8').includes('provider = "sqlite"')) {
    throw new Error('Reviewed SQLite migrations are missing. No database mutation was attempted; do not use db push on existing data.');
  }
  const databasePath = sqliteFileFromDatabaseUrl(process.env.DATABASE_URL || '');
  const migrationReadiness = inspectMigrationReadiness(databasePath);
  if (!migrationReadiness.ok) {
    throw new Error(`Refusing automatic database migration: ${migrationReadiness.reason}. No migration command was run.`);
  }
  mkdirSync(path.dirname(databasePath), { recursive: true });
  try {
    runCommand(npmCommand(), ['run', 'db:migrate:deploy'], 'Database migration');
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    if (existsSync(databasePath)) {
      const baseline = inspectExistingDatabase(databasePath);
      if (baseline.ok) {
        throw new Error(`${detail} The read-only comparison matches the original baseline. Prisma may have created an empty migration-history table before failing; back up first, then use \`npm run aloapi -- baseline-existing\` to record the verified baseline and apply only reviewed additive migrations.`);
      }
    }
    throw error;
  }
  runCommand(npmCommand(), ['run', 'db:generate'], 'Prisma Client generation');
  runCommand(npmCommand(), ['run', 'vault:migrate:credentials'], 'Encrypted credential migration');
  if (!dev) runCommand(npmCommand(), ['run', 'build'], 'Production build');

  const instanceId = config.instanceId;
  const args = dev
    ? [NEXT_BIN, 'dev', '--hostname', config.host, '--port', String(config.port)]
    : [STANDALONE_SERVER];
  if (!dev && !existsSync(STANDALONE_SERVER)) throw new Error('Production server build is missing after `npm run build`.');
  const logFd = openSync(LOG_FILE, 'a', 0o600);
  const child = spawn(process.execPath, args, {
    cwd: ROOT,
    detached: true,
    stdio: ['ignore', logFd, logFd],
    env: { ...process.env, NODE_ENV: dev ? 'development' : 'production', HOSTNAME: config.host, PORT: String(config.port), ALOAPI_INSTANCE_ID: instanceId },
  });
  closeSync(logFd);
  child.unref();
  writeFileSync(PID_FILE, JSON.stringify({ pid: child.pid, port: config.port, host: config.host, instanceId, startedAt: new Date().toISOString(), dev }, null, 2), { mode: 0o600 });

  const deadline = Date.now() + 45_000;
  let health = null;
  while (Date.now() < deadline) {
    health = await requestHealth(config.url);
    if (health?.instanceId === instanceId) break;
    await new Promise(resolve => setTimeout(resolve, 300));
  }
  if (!health || health.instanceId !== instanceId) {
    try { process.kill(child.pid, 'SIGTERM'); } catch { /* already exited */ }
    console.error(`ALOAPI did not become healthy. See ${LOG_FILE}`);
    process.exitCode = 1;
    return;
  }

  console.log(`ALOAPI ${dev ? 'development service' : 'service'} is ready at ${config.url}`);
  console.log(`Service log: ${LOG_FILE}`);
  if (!noOpen) openBrowser(config.url);
}

function openBrowser(url, platform = process.platform) {
  const invocation = browserInvocation(platform, url);
  try {
    const child = spawn(invocation.command, invocation.args, { detached: true, stdio: 'ignore', shell: platform === 'win32' });
    child.on('error', error => console.warn(`Could not open a browser automatically: ${error.message}`));
    child.unref();
  } catch (error) {
    console.warn(`Could not open a browser automatically: ${error instanceof Error ? error.message : String(error)}`);
    console.log(`Open ${url} in a browser.`);
  }
}

async function stopService() {
  if (!existsSync(PID_FILE)) { console.log('ALOAPI is not running (no service PID file).'); return; }
  let record;
  try { record = JSON.parse(readFileSync(PID_FILE, 'utf8')); }
  catch { rmSync(PID_FILE, { force: true }); console.log('Removed a malformed stale PID file; no process was stopped.'); return; }
  const port = parsePort(record.port, DEFAULT_PORT);
  const url = serviceUrl(port, record.host || DEFAULT_HOST);
  const health = await requestHealth(url);
  if (!health || health.instanceId !== record.instanceId) {
    rmSync(PID_FILE, { force: true });
    console.log('No matching ALOAPI instance responded; removed stale PID file without signalling another process.');
    return;
  }
  try { process.kill(record.pid, 'SIGTERM'); }
  catch (error) { throw new Error(`Could not stop ALOAPI PID ${record.pid}: ${error instanceof Error ? error.message : String(error)}`); }
  const deadline = Date.now() + 10_000;
  while (Date.now() < deadline) {
    if (!(await requestHealth(url))) break;
    await new Promise(resolve => setTimeout(resolve, 250));
  }
  rmSync(PID_FILE, { force: true });
  console.log('ALOAPI stopped. The SQLite database and .env were not modified.');
}

async function showStatus() {
  const config = runtimeConfig();
  const health = await requestHealth(config.url);
  if (!health) { console.log(`ALOAPI is not responding at ${config.url}.`); return; }
  console.log(`ALOAPI responds at ${config.url}; service: ${health.status ?? 'unknown'}; database: ${health.database ?? 'unknown'}; instance: ${health.instanceId ?? 'unmanaged'}.`);
  if (existsSync(PID_FILE)) {
    try {
      const record = JSON.parse(readFileSync(PID_FILE, 'utf8'));
      if (record.instanceId === health.instanceId) console.log(`Managed process PID: ${record.pid}; started: ${record.startedAt}`);
    } catch { /* the health result is still useful */ }
  }
}

function baselineExisting() {
  loadLocalEnv();
  const databasePath = sqliteFileFromDatabaseUrl(process.env.DATABASE_URL || '');
  const result = inspectExistingDatabase(databasePath);
  if (!result.ok) throw new Error(`Refusing to baseline ${databasePath}: ${result.reason}. No data or schema was changed. Use a reviewed migration for any other schema.`);
  const prismaEntry = path.join(ROOT, 'node_modules', 'prisma', 'build', 'index.js');
  if (!existsSync(prismaEntry)) throw new Error('Local Prisma CLI is missing. Run npm ci before baselining.');
  console.log(`Verified existing SQLite schema: ${result.reason}.`);
  console.log('Recording the original schema as applied, then applying only the checked-in additive migrations. Existing rows are not rewritten.');
  runCommand(process.execPath, [prismaEntry, 'migrate', 'resolve', '--applied', '20261115000000_baseline', '--schema', 'prisma/schema.prisma'], 'Baseline verification');
  runCommand(npmCommand(), ['run', 'db:migrate:deploy'], 'Additive database migrations');
  console.log('Existing database safely baselined; additive migrations applied. No db push, reset, drop, or data deletion was used.');
}

function setup() {
  const created = writeInitialEnv();
  if (!created) {
    console.log(`${ENV_FILE} already exists; it was left unchanged. Review ALOAPI_HOST/PORT and ALOAPI_VAULT_KEY yourself.`);
    return;
  }
  console.log(`Created private local configuration at ${ENV_FILE}.`);
  console.log(`One-time administrator username: ${created.username}`);
  console.log(`One-time administrator password: ${created.password}`);
  console.log(`The service binds only to loopback port ${DEFAULT_PORT}; the generated vault key is stored in .env.`);
  console.log('Keep .env backed up securely. Remove the bootstrap username/password after first login; never change the vault key while encrypted data exists.');
  console.log('Run `npm run aloapi -- start` to apply migrations, build, start the service, and open the browser.');
}

function help() {
  console.log(`ALOAPI local service CLI\n\nUsage:\n  npm run aloapi -- setup                 Create private .env and one-time admin credentials\n  npm run aloapi -- start [--no-open]     Apply safe migrations, build, start on loopback, and open browser\n  npm run aloapi -- start --dev            Apply safe migrations and run the dev server on loopback\n  npm run aloapi -- baseline-existing     Strictly verify an old SQLite schema, then mark/apply additive migrations\n  npm run aloapi -- status                Check the local health endpoint\n  npm run aloapi -- stop                  Stop only the matching managed ALOAPI instance\n  npm run aloapi -- open                  Open the local app in a browser\n`);
}

export function parseArgs(args) {
  const command = args[0] || 'start';
  return { command, dev: args.includes('--dev'), noOpen: args.includes('--no-open') };
}

async function main() {
  const { command, dev, noOpen } = parseArgs(process.argv.slice(2));
  if (command === 'help' || command === '--help' || command === '-h') return help();
  if (command === 'setup') return setup();
  if (command === 'run-server') return runServerForeground(false, runtimeConfig());
  if (command === 'start') return startBackground({ dev, noOpen });
  if (command === 'stop') return stopService();
  if (command === 'status') return showStatus();
  if (command === 'baseline-existing') return baselineExisting();
  if (command === 'open') {
    const config = runtimeConfig();
    openBrowser(config.url);
    return;
  }
  console.error(`Unknown command: ${command}`);
  help();
  process.exitCode = 2;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch(error => {
    console.error(`ALOAPI: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  });
}
