export const MODULE_INDEX = new Map<string, FirstPartyModuleDefinition>(
  FIRST_PARTY_MODULES.map(m => [m.key, m]),
);

export function getFirstPartyModule(key: string): FirstPartyModuleDefinition | undefined {
  return MODULE_INDEX.get(key);
}

/**
 * Enforces Requirement A/B boundary: no first-party platform module key may appear inside the external provider catalog.
 */
export function assertFirstPartyExternalSeparation() {
  const externalKeys = new Set(ALL_INTEGRATION_CATALOG.map(p => p.key));
  const collisions = FIRST_PARTY_MODULES.filter(m => externalKeys.has(m.key)).map(m => m.key);
  if (collisions.length > 0) {
    throw new Error(`First-party module keys collided with external catalog: ${collisions.join(', ')}`);
  }
  return { ok: true, firstPartyCount: FIRST_PARTY_MODULES.length, externalCount: ALL_INTEGRATION_CATALOG.length };
}
